import streamlit as st

from src import analytics, charts, ui

df = ui.page_context()
ui.page_header("Executive Overview", "Ticket volume, priority mix, SLA health and model quality at a glance.")
if st.session_state["is_demo"]:
    ui.note("You are viewing a bundled SYNTHETIC demo dataset generated by scripts/generate_sample_data.py. All figures below describe that demo data only. Upload your own CSV on the Data Import page.")
if df.empty:
    ui.empty_state("No tickets match the current filters", "Widen or reset the filters in the sidebar.")
    st.stop()

dk = ui.dark()
k = analytics.kpis(df)
clf, clf_msg = ui.get_classifier("category")
D = analytics.KPI_DEFINITIONS
vc = k["volume_change_pct"]
vc_sub = ("Needs 60+ days of data" if vc is None else f'<span class="{"up" if vc > 0 else "down"}">{"▲" if vc > 0 else "▼"} {abs(vc):.1f}%</span> last 30d vs prior 30d')
ui.kpi_cards([
    ("Total tickets", f'{k["total"]:,}', vc_sub, D["Total tickets"] + " " + D["Volume vs prior period"]),
    ("Open / unresolved", None if k["open"] is None else f'{k["open"]:,}', "" if k["open"] is None else f'{k["open"] / k["total"] * 100:.1f}% of tickets', D["Open / unresolved"]),
    ("High-priority share", None if k["high_priority_pct"] is None else f'{k["high_priority_pct"]:.1f}%', "High + Critical", D["High-priority share"]),
    ("Avg first response", None if k["avg_first_response_h"] is None else analytics.format_hours(k["avg_first_response_h"]), "answered tickets only", D["Avg first response"]),
    ("Median resolution", None if k["median_resolution_h"] is None else analytics.format_hours(k["median_resolution_h"]), "resolved tickets only", D["Median resolution"]),
    ("SLA breach rate", None if k["sla_breach_rate"] is None else f'{k["sla_breach_rate"]:.1f}%', f'{k["sla_known"]:,} tickets with deadlines' if k["sla_known"] else "needs sla_deadline", D["SLA breach rate"]),
    ("Classifier macro-F1", None if clf is None else f'{clf.metrics["macro_f1"]:.3f}', "test set n=%d" % clf.n_test if clf else (clf_msg or "")[:60], D["Classifier macro-F1"]),
])

c1, c2 = st.columns([2, 1])
with c1:
    freq = st.radio("Trend granularity", ["D", "W", "M"], horizontal=True, format_func={"D": "Daily", "W": "Weekly", "M": "Monthly"}.get, key="ov_freq")
    tr = analytics.volume_trend(df, freq)
    if tr.empty:
        ui.empty_state("Trend not available", "No valid created_at timestamps.")
    else:
        st.plotly_chart(charts.trend_line(tr, "Ticket volume over time", dk), width="stretch")
with c2:
    pc = analytics.count_by(df, "priority")
    if pc is None:
        ui.empty_state("Priority not available", "No priority column mapped.")
    else:
        ev = st.plotly_chart(charts.priority_bar(pc, dk), width="stretch", on_select="rerun", selection_mode="points", key="ov_prio")
        pts = ev.selection.points if ev and ev.selection else []
        if pts:
            ui.set_filter_from_chart("f_priority", str(pts[0]["x"]))
        st.caption("Click a bar to filter the whole app.")

c3, c4 = st.columns(2)
with c3:
    cc = analytics.count_by(df, "category")
    if cc is None:
        ui.empty_state("Categories not available", "No category column mapped.")
    else:
        ev = st.plotly_chart(charts.bar_h(cc, "category", "tickets", "Tickets by category", dk), width="stretch", on_select="rerun", selection_mode="points", key="ov_cat")
        pts = ev.selection.points if ev and ev.selection else []
        if pts:
            ui.set_filter_from_chart("f_category", str(pts[0]["y"]))
        st.caption("Click a bar to filter the whole app.")
with c4:
    if "product" in df and "channel" in df and df["product"].notna().any() and df["channel"].notna().any():
        st.plotly_chart(charts.stacked_bar(df, "product", "channel", "Product by channel", dk), width="stretch")
    else:
        ui.empty_state("Product / channel breakdown not available", "Map the product and channel columns to enable it.")

c5, c6 = st.columns(2)
with c5:
    if "resolution_hours" in df and df["resolution_hours"].notna().any():
        st.plotly_chart(charts.histogram(df["resolution_hours"], "Resolution time distribution (top 2% trimmed for readability)", "Hours to resolve", dk), width="stretch")
    else:
        ui.empty_state("Resolution time not available", "Needs created_at and resolved_at.")
with c6:
    m = analytics.category_priority_matrix(df)
    if m is None:
        ui.empty_state("Heatmap not available", "Needs category and priority.")
    else:
        st.plotly_chart(charts.heatmap(m, "Category × priority", dk), width="stretch")

st.subheader("Recent ticket activity")
cols = [c for c in ("ticket_id", "created_at", "subject", "category", "priority", "status", "product", "channel") if c in df]
recent = df.sort_values("created_at", ascending=False).head(15)[cols] if "created_at" in df else df.head(15)[cols]
st.dataframe(recent, width="stretch", hide_index=True)
with st.expander("KPI definitions"):
    for name, text in D.items():
        st.markdown(f"**{name}** — {text}")
